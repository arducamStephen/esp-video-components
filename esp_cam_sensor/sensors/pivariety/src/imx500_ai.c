/* Moves the IMX500 internal state machine between states or updates.
 *
 * Prerequisites: Sensor is powered on and not currently streaming
 */
static int imx500_state_transition(struct imx500 *imx500, const uint8_t *fw, size_t fw_size,
                                    enum imx500_image_type type, bool update)
{
	// struct i2c_client *client = v4l2_get_subdevdata(&imx500->sd);
	struct imx500_reg_sequence cmd_reply_sts_cnt_reg;
	size_t valid_size;
	int ret;
	uint32_t tmp;

	if (!imx500 || !fw || type >= TYPE_MAX){
		return -1;	//-EINVAL;
	}
		

	if (!update && (int)type != (int)imx500->fsm_state){
		return -1;	//-EINVAL;
	}

	/* Validate firmware */
	valid_size = imx500_valid_fw_bytes(fw, fw_size);
	if (!valid_size){
		return -1;	//-EINVAL;
	}

	ret = imx500_prepare_poll_cmd_reply_sts(imx500->sccb_handle, &cmd_reply_sts_cnt_reg);
	if (ret)
		return ret;

	ESP_LOGI(TAG, "imx500_prepare_poll_cmd_reply_sts val=%d", cmd_reply_sts_cnt_reg.val);

	struct imx500_reg_sequence common_regs[] = {
		{ IMX500_REG_DD_FLASH_TYPE, 0x02 },
		{ IMX500_REG_DD_LOAD_MODE, IMX500_DD_LOAD_MODE_AP },
		{ IMX500_REG_DD_IMAGE_TYPE, type },
		{ IMX500_REG_DD_DOWNLOAD_DIV_NUM, (valid_size - 1) / ONE_MIB },
		{ IMX500_REG_DD_DOWNLOAD_FILE_SIZE, valid_size },
	};

	struct imx500_reg_sequence state_transition_regs[] = {
		{ IMX500_REG_DD_ST_TRANS_CMD, type },
		{ IMX500_REG_DD_CMD_INT, IMX500_DD_CMD_INT_ST_TRANS },
	};

	struct imx500_reg_sequence update_regs[] = {
		{ IMX500_REG_DD_UPDATE_CMD, IMX500_DD_UPDATE_CMD_SRAM },
		{ IMX500_REG_DD_CMD_INT, IMX500_DD_CMD_INT_UPDATE },
	};

	ret = imx500ai_multi_reg_write(imx500->sccb_handle, common_regs, ARRAY_SIZE(common_regs));

	ret = imx500ai_multi_reg_write(imx500->sccb_handle, update ? update_regs : state_transition_regs, 2);
	if (ret)
		return ret;

	// ret = imx500ai_multi_reg_read(imx500->sccb_handle, common_regs, ARRAY_SIZE(common_regs));
	// ret = imx500ai_multi_reg_read(imx500->sccb_handle, update ? update_regs : state_transition_regs, 2);


	/* Poll CMD_REPLY_STS_CNT until a response is available */
	ret = imx500_poll_status_reg(imx500->sccb_handle, &cmd_reply_sts_cnt_reg, 5);
	if (ret) {
        ESP_LOGE(TAG, "DD_REF_STS register did not update\n");
		return ret;
	}
	ESP_LOGI(TAG, "imx500_poll_status_reg val=%d", cmd_reply_sts_cnt_reg.val);

	/* Read response to state transition / update request */
	ret = imx500ai_read(imx500->sccb_handle, IMX500_REG_DD_CMD_REPLY_STS, &tmp);
	// ESP_LOGI(TAG, "IMX500_REG_DD_CMD_REPLY_STS tmp=%d, update=%d\n", tmp, update);

	if (ret || tmp != (update ? IMX500_DD_CMD_REPLY_STS_UPDATE_READY :
				    IMX500_DD_CMD_REPLY_STS_TRANS_READY))
		return ret ? ret : -2;	//-EBUSY;

	imx500->fw_stage = type;
	imx500->fw_progress = 0;

	for (size_t i = 0; i <= valid_size / ONE_MIB; i++) {
		const uint8_t *data = fw + (i * ONE_MIB);
		size_t size = valid_size - (i * ONE_MIB);
		struct imx500_reg_sequence download_sts_reg = {
			IMX500_REG_DD_DOWNLOAD_STS,
			IMX500_DD_DOWNLOAD_STS_DOWNLOADING,
		};

		/* Calculate SPI xfer size avoiding 0-sized TXNs */
		size = MIN(size, ONE_MIB);
		if (!size)
			break;

		/* Poll until device is ready for download */
		ret = imx500_poll_status_reg(imx500->sccb_handle, &download_sts_reg, 100);
		if (ret) {
			ESP_LOGE(TAG, "DD_DOWNLOAD_STS was never ready\n");
			return ret;
		}
		// ESP_LOGI(TAG, "imx500_poll_status_reg download sts, reg=0x%x, val=%d\n", download_sts_reg.reg, download_sts_reg.val);

		/* Do SPI transfer */
		// gpiod_set_value_cansleep(imx500->led_gpio, 1);
		ret = imx500_spi_write(data, size);
		// gpiod_set_value_cansleep(imx500->led_gpio, 0);

		imx500->fw_progress += size;

		if (ret < 0)
			return ret;
	}

	/* Poll until another response is available */
	ret = imx500_poll_status_reg(imx500->sccb_handle, &cmd_reply_sts_cnt_reg, 5);
	ESP_LOGI(TAG, "imx500_poll_status_reg val=%d", cmd_reply_sts_cnt_reg.val);
	if (ret) {
		ESP_LOGE(TAG, "DD_REF_STS register did not update after SPI write(s)\n");
		return ret;
	}

	/* Verify that state transition / update completed successfully */
	ret = imx500ai_read(imx500->sccb_handle, IMX500_REG_DD_CMD_REPLY_STS, &tmp);
	if (ret || tmp != (update ? IMX500_DD_CMD_REPLY_STS_UPDATE_DONE :
				    IMX500_DD_CMD_REPLY_STS_TRANS_DONE))
		return ret ? ret : -3;	//-EREMOTEIO;

	if (!update && imx500->fsm_state < IMX500_STATE_WITH_NETWORK)
		imx500->fsm_state++;

	imx500->fw_progress = fw_size;

	return 0;
}

static int imx500_transition_to_standby_wo_network(struct imx500 *imx500)
{
	// struct i2c_client *client = v4l2_get_subdevdata(&imx500->sd);
	const struct firmware *firmware;
	uint32_t fw_ver;
	int ret;

	firmware = imx500->fw_loader;
	ret = imx500_state_transition(imx500, firmware->data, firmware->size,
				      TYPE_LOADER, false);
	if (ret) {
        ESP_LOGE(TAG, "%s: failed to load loader firmware\n", __func__);
		return ret;
	}
	ESP_LOGI(TAG, "load loader firmware OK!");

	firmware = imx500->fw_main;
	ret = imx500_state_transition(imx500, firmware->data, firmware->size,
				      TYPE_MAIN, false);
	if (ret) {
        ESP_LOGE(TAG, "%s: failed to load main firmwar\n", __func__);
		return ret;
	}
	ESP_LOGI(TAG, "load main firmware OK!");

	ret = imx500ai_read(imx500->sccb_handle, IMX500_REG_MAIN_FW_VERSION, &fw_ver);
	if (ret) {
        ESP_LOGE(TAG, "%s: could not read main firmware version\n", __func__);
		return ret;
	}

	ESP_LOGI(TAG, "main firmware version: %u%u.%u%u.%u%u",
		 (fw_ver >> 20) & 0xF, (fw_ver >> 16) & 0xF,
		 (fw_ver >> 12) & 0xF, (fw_ver >> 8) & 0xF, (fw_ver >> 4) & 0xF,
		 fw_ver & 0xF);

	ret = imx500ai_multi_reg_write(imx500->sccb_handle, metadata_output,
				  ARRAY_SIZE(metadata_output));
	if (ret) {
		ESP_LOGE(TAG, "%s: failed to configure MIPI output for DNN\n", __func__);
		return ret;
	}

	ret = imx500ai_multi_reg_write(imx500->sccb_handle, dnn_regs,
				  ARRAY_SIZE(dnn_regs));
	if (ret) {
		ESP_LOGE(TAG, "%s: unable to write DNN regs\n",	__func__);
		return ret;
	}

	return 0;
}

static int imx500_transition_to_network(struct imx500 *imx500)
{
	// struct i2c_client *client = v4l2_get_subdevdata(&imx500->sd);
	uint32_t imx500_fsm_state;
	int ret;

	ret = imx500_iterate_nw_regs(imx500->fw_network,
				     imx500->fw_network_size, imx500,
				     imx500_reg_val_write_cbk);
	if (ret) {
		ESP_LOGE(TAG, "%s: unable to apply register writes from firmware\n", __func__);
		return ret;
	}

	/* Read IMX500 state to determine whether transition or update is required */
	ret = imx500ai_read(imx500->sccb_handle, IMX500_REG_DD_SYS_STATE,
		       &imx500_fsm_state);
	if (ret || imx500_fsm_state & 1)
		return ret ? ret : -121;	//-EREMOTEIO;

	ret = imx500_state_transition(
		imx500, imx500->fw_network, imx500->fw_network_size,
		TYPE_NW_WEIGHTS,
		imx500_fsm_state == IMX500_DD_SYS_STATE_STANDBY_WITH_NETWORK);
	if (ret) {
		ESP_LOGE(TAG, "%s: failed to load network weights\n", __func__);
		return ret;
	}
	ESP_LOGI(TAG, "load network weights OK!");

	/* Select network 0 */
	ret = imx500ai_write(imx500->sccb_handle, IMX500_REG8(0xD701), 0);
	if (ret) {
		ESP_LOGE(TAG, "%s: failed to select network 0\n", __func__);
		return ret;
	}

	return ret;
}


