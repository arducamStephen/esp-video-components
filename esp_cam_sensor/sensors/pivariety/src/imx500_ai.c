/* reg is both input and output:
 * reg->val is the value we're polling until we're NEQ to
 * It is then populated with the updated value.
 */
static int /*__must_check*/
imx500_poll_status_reg(esp_sccb_io_handle_t sccb_handle,
					       struct imx500_reg_sequence *reg,
					       uint8_t timeout)
{
	uint32_t read_value;
	int ret;

	while (timeout) {
		ret = imx500ai_read(sccb_handle, reg->reg, &read_value);
		if (ret)
			return ret;

		if (read_value != reg->val) {
			reg->val = read_value;
			return 0;
		}

		timeout--;
		delay_ms(50);
	}
	return -1;	//-EAGAIN;
}

static int imx500_prepare_poll_cmd_reply_sts(esp_sccb_io_handle_t sccb_handle,
					     struct imx500_reg_sequence *cmd_reply)
{
	/* Perform single-byte read of 4-byte IMX500_REG_DD_REF_STS register to
	 * target CMD_REPLY_STS_CNT sub-register
	 */
	cmd_reply->reg = IMX500_REG8(IMX500_REG_ADDR(IMX500_REG_DD_REF_STS));

	return imx500ai_read(sccb_handle, cmd_reply->reg, &cmd_reply->val);
}

